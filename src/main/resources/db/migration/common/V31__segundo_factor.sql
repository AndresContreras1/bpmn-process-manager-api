-- PR 49: el segundo factor de cada persona. El secreto del TOTP se guarda cifrado con AES-GCM, nunca en claro: con una
-- copia de la base no se generan codigos. confirmado_en queda vacio hasta que la persona prueba que su aplicacion
-- genera bien los codigos; hasta entonces el login no se lo pide. ultimo_paso es el paso de 30 segundos del ultimo
-- codigo aceptado: uno igual o anterior ya no entra.
create table segundos_factores (
    id               bigint generated by default as identity primary key,
    empresa_id       bigint       not null,
    usuario_id       bigint       not null,
    secreto_cifrado  varchar(200) not null,
    creado_en        timestamp(6) not null,
    confirmado_en    timestamp(6),
    ultimo_paso      bigint       default 0 not null,
    constraint fk_segundos_factores_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_segundos_factores_usuario foreign key (usuario_id) references usuarios (id),
    constraint uk_segundos_factores_usuario unique (usuario_id)
);
create index idx_segundos_factores_empresa on segundos_factores (empresa_id);

-- Diez codigos por persona, de un solo uso, para entrar si pierde el telefono. Se guarda su HMAC-SHA256, con una
-- clave que no esta en la base: tienen 50 bits, y un SHA-256 a secas se recorreria entero con una copia de la tabla.
create table codigos_de_recuperacion (
    id           bigint generated by default as identity primary key,
    empresa_id   bigint       not null,
    usuario_id   bigint       not null,
    codigo_hash  varchar(64)  not null,
    creado_en    timestamp(6) not null,
    usado_en     timestamp(6),
    constraint fk_codigos_de_recuperacion_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_codigos_de_recuperacion_usuario foreign key (usuario_id) references usuarios (id),
    constraint uk_codigos_de_recuperacion_hash unique (usuario_id, codigo_hash)
);
create index idx_codigos_de_recuperacion_empresa on codigos_de_recuperacion (empresa_id);
