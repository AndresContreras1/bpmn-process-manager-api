-- PR 70: a quien le llega una tarea, lo que se hace con ella mientras espera y quien la puede completar.

-- La regla de asignacion de una actividad de usuario. Vacia es la de siempre: la tarea espera en la bandeja del rol de
-- su lane. PERSONA la da a alguien fijo (asignacion_usuario_id), INICIADOR a quien abrio el caso y CAMPO a la persona
-- que dice una variable del caso (asignacion_campo), la que escribio un campo PERSONA de un formulario anterior. La
-- persona fija no lleva clave foranea: un BPMN importado de otra tienda puede traer un id que aqui no es nadie, y eso
-- no se descubre al guardar sino al crear la tarea, que entonces se queda en la bandeja del rol.
alter table nodos_flujo add column asignacion varchar(20);
alter table nodos_flujo add column asignacion_usuario_id bigint;
alter table nodos_flujo add column asignacion_campo varchar(200);
alter table nodos_flujo add constraint ck_nodos_flujo_asignacion
    check (asignacion is null and asignacion_usuario_id is null and asignacion_campo is null
        or asignacion = 'PERSONA' and asignacion_usuario_id is not null and asignacion_campo is null
        or asignacion = 'INICIADOR' and asignacion_usuario_id is null and asignacion_campo is null
        or asignacion = 'CAMPO' and asignacion_usuario_id is null and asignacion_campo is not null);
-- Solo una tarea de usuario espera a una persona; el servicio no deja ponerla en otro nodo, y esto lo sostiene.
alter table nodos_flujo add constraint ck_nodos_flujo_asignacion_de_usuario
    check (asignacion is null or tipo_nodo = 'ACTIVIDAD' and tipo_actividad = 'USUARIO');

-- Quien abrio el caso a mano: a quien va una tarea asignada al iniciador. Vacio en los que abrio un mensaje o un
-- temporizador, y en los de antes.
alter table casos add column iniciado_por bigint;
alter table casos add constraint fk_casos_iniciado_por foreign key (iniciado_por) references usuarios (id);
create index idx_casos_iniciado_por on casos (iniciado_por);

-- Quien delego la tarea que ahora tiene otra persona: a quien vuelve si el delegado la suelta.
alter table actividades_caso add column delegada_por bigint;
alter table actividades_caso add constraint fk_actividades_caso_asignado_a foreign key (asignado_a) references usuarios (id);
alter table actividades_caso add constraint fk_actividades_caso_delegada_por
    foreign key (delegada_por) references usuarios (id);
alter table actividades_caso add constraint ck_actividades_caso_delegada
    check (delegada_por is null or asignado_a is not null and asignado_a <> delegada_por);
-- Las bandejas: lo de una persona y lo que nadie tiene, de lo que espera.
create index idx_actividades_caso_asignado on actividades_caso (empresa_id, asignado_a, estado);
create index idx_actividades_caso_delegada_por on actividades_caso (delegada_por);

-- Cada delegacion de una tarea, con su motivo y como termino: devuelta, completada por el delegado o anulada porque
-- alguien la reasigno o la solto. Mientras esta ACTIVA, la tarea la tiene a_usuario_id y vuelve a de_usuario_id.
create table delegaciones (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    actividad_caso_id  bigint        not null,
    caso_id            bigint        not null,
    de_usuario_id      bigint        not null,
    a_usuario_id       bigint        not null,
    motivo             varchar(500)  not null,
    estado             varchar(20)   not null,
    cerrada_en         timestamp(6),
    version            bigint        default 0 not null,
    creado_por         bigint,
    fecha_creacion     timestamp(6)  not null,
    modificado_por     bigint,
    fecha_modificacion timestamp(6)  not null,
    constraint fk_delegaciones_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_delegaciones_actividad foreign key (actividad_caso_id) references actividades_caso (id),
    constraint fk_delegaciones_caso foreign key (caso_id) references casos (id),
    constraint fk_delegaciones_de foreign key (de_usuario_id) references usuarios (id),
    constraint fk_delegaciones_a foreign key (a_usuario_id) references usuarios (id),
    constraint ck_delegaciones_estado check (estado in ('ACTIVA', 'DEVUELTA', 'COMPLETADA', 'ANULADA')),
    constraint ck_delegaciones_personas check (de_usuario_id <> a_usuario_id),
    constraint ck_delegaciones_cierre check (estado = 'ACTIVA' and cerrada_en is null
                                             or estado <> 'ACTIVA' and cerrada_en is not null)
);
create index idx_delegaciones_empresa on delegaciones (empresa_id);
create index idx_delegaciones_actividad on delegaciones (actividad_caso_id);
create index idx_delegaciones_caso on delegaciones (caso_id);
create index idx_delegaciones_de on delegaciones (de_usuario_id);
create index idx_delegaciones_a on delegaciones (a_usuario_id);
-- Una tarea tiene a lo sumo una delegacion abierta.
create unique index uq_delegaciones_activa on delegaciones (actividad_caso_id) where estado = 'ACTIVA';

-- La politica de la tienda: un administrador completa la tarea que tiene otra persona. Apagada de fabrica.
alter table configuracion_tienda add column administrador_completa_por_otro boolean default false not null;

-- La linea de tiempo del caso cuenta a quien le llego cada tarea y lo que se hizo con ella.
alter table eventos_caso drop constraint ck_eventos_caso_tipo;
alter table eventos_caso add constraint ck_eventos_caso_tipo check (tipo in ('CASO_ABIERTO', 'NODO_ACTIVADO',
    'TAREA_CREADA', 'TAREA_COMPLETADA', 'GATEWAY_DECIDIO', 'MENSAJE_ENVIADO', 'MENSAJE_RECIBIDO', 'ENVIO_FALLIDO',
    'SIN_CAMINO', 'VARIABLE_AUSENTE', 'CASO_TERMINADO', 'CASO_CANCELADO', 'TEMPORIZADOR_PROGRAMADO',
    'TEMPORIZADOR_DISPARADO', 'TAREA_ASIGNADA', 'TAREA_RECLAMADA', 'TAREA_LIBERADA', 'TAREA_REASIGNADA',
    'TAREA_DELEGADA'));

-- PR 51: como toda tabla de una tienda, solo sus filas.
alter table delegaciones enable row level security;
alter table delegaciones force row level security;
create policy aislamiento_por_tienda on delegaciones
    using (current_setting('app.sistema', true) = 'on'
           or empresa_id = nullif(current_setting('app.empresa_id', true), '')::bigint)
    with check (current_setting('app.sistema', true) = 'on'
                or empresa_id = nullif(current_setting('app.empresa_id', true), '')::bigint);
