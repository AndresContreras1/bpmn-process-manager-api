-- PR 55: lo que BPMN tiene para describir un proceso aunque no corra. Un proceso documental se publica y se
-- documenta, pero no abre casos; uno ejecutable es lo que habia hasta ahora, y es lo que son todos los que ya existian.
alter table procesos add column modo varchar(20) default 'EJECUTABLE' not null;
alter table procesos add constraint ck_procesos_modo check (modo in ('DOCUMENTAL', 'EJECUTABLE'));

-- La tarea sin tipo, los eventos de temporizador (inicio, espera y de borde) y el fin que termina el caso entero.
alter table nodos_flujo drop constraint ck_nodos_flujo_tipo_actividad;
alter table nodos_flujo add constraint ck_nodos_flujo_tipo_actividad
    check (tipo_actividad in ('USUARIO', 'SERVICIO', 'ENVIO', 'RECEPCION', 'SIN_TIPO'));
alter table nodos_flujo drop constraint ck_nodos_flujo_tipo_evento;
alter table nodos_flujo alter column tipo_evento type varchar(30);
alter table nodos_flujo add constraint ck_nodos_flujo_tipo_evento
    check (tipo_evento in ('INICIO', 'FIN', 'MENSAJE_INICIO', 'MENSAJE_INTERMEDIO', 'MENSAJE_FIN',
                           'TEMPORIZADOR_INICIO', 'TEMPORIZADOR_INTERMEDIO', 'TEMPORIZADOR_BORDE', 'FIN_TERMINACION'));

-- El temporizador: una duracion (P3D), una fecha (2026-12-24T09:00:00Z) o un ciclo (R3/PT1H), en ISO 8601. Un evento
-- de borde va pegado a una actividad, y la interrumpe o no.
alter table nodos_flujo add column tipo_temporizador varchar(20);
alter table nodos_flujo add column temporizador varchar(120);
alter table nodos_flujo add column adjunto_a_id bigint;
alter table nodos_flujo add column interrumpe boolean;
alter table nodos_flujo add constraint ck_nodos_flujo_tipo_temporizador
    check (tipo_temporizador in ('DURACION', 'FECHA', 'CICLO'));
alter table nodos_flujo add constraint fk_nodos_flujo_adjunto_a foreign key (adjunto_a_id) references nodos_flujo (id);
create index idx_nodos_flujo_adjunto_a on nodos_flujo (adjunto_a_id);

-- Anotaciones, grupos, objetos de datos y almacenes. Van en una lane (con su posicion relativa, como los nodos) o
-- sueltos en el diagrama (con su posicion en el dibujo).
create table artefactos (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    proceso_id         bigint        not null,
    bpmn_id            varchar(64)   not null,
    tipo               varchar(20)   not null,
    texto              varchar(1000),
    pool_id            bigint,
    lane_id            bigint,
    posicion_x         integer       not null,
    posicion_y         integer       not null,
    ancho              integer       not null,
    alto               integer       not null,
    activo             boolean       default true not null,
    version            bigint        default 0 not null,
    creado_por         bigint,
    fecha_creacion     timestamp(6)  not null,
    modificado_por     bigint,
    fecha_modificacion timestamp(6)  not null,
    constraint fk_artefactos_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_artefactos_proceso foreign key (proceso_id) references procesos (id),
    constraint fk_artefactos_pool foreign key (pool_id) references pools (id),
    constraint fk_artefactos_lane foreign key (lane_id) references lanes (id),
    constraint ck_artefactos_tipo check (tipo in ('ANOTACION', 'GRUPO', 'OBJETO_DATOS', 'ALMACEN_DATOS')),
    constraint ck_artefactos_tamano check (ancho > 0 and alto > 0)
);
create index idx_artefactos_empresa on artefactos (empresa_id);
create index idx_artefactos_proceso on artefactos (proceso_id);
create index idx_artefactos_pool on artefactos (pool_id);
create index idx_artefactos_lane on artefactos (lane_id);

-- Lo que une un artefacto con otro elemento: una asociacion (de una anotacion, por ejemplo) o un dato que entra a una
-- tarea o sale de ella. Los extremos se nombran por su bpmn_id: pueden ser nodos, flujos o artefactos.
create table asociaciones (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    proceso_id         bigint        not null,
    bpmn_id            varchar(64)   not null,
    tipo               varchar(20)   not null,
    origen             varchar(64)   not null,
    destino            varchar(64)   not null,
    direccion          varchar(20)   default 'NINGUNA' not null,
    activo             boolean       default true not null,
    version            bigint        default 0 not null,
    creado_por         bigint,
    fecha_creacion     timestamp(6)  not null,
    modificado_por     bigint,
    fecha_modificacion timestamp(6)  not null,
    constraint fk_asociaciones_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_asociaciones_proceso foreign key (proceso_id) references procesos (id),
    constraint ck_asociaciones_tipo check (tipo in ('ASOCIACION', 'ENTRADA_DATOS', 'SALIDA_DATOS')),
    constraint ck_asociaciones_direccion check (direccion in ('NINGUNA', 'UNA', 'AMBAS'))
);
create index idx_asociaciones_empresa on asociaciones (empresa_id);
create index idx_asociaciones_proceso on asociaciones (proceso_id);

