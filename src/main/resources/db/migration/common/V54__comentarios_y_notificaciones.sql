-- PR 63: los comentarios de un proceso, en hilos. Un hilo es un comentario sin padre, pegado al proceso, a un elemento
-- (bpmn_id) y a una version publicada si se dice; sus respuestas tienen padre y heredan todo eso. Solo el primero de un
-- hilo se resuelve. Se guarda el Markdown y el HTML ya saneado, como la documentacion; las menciones son ids de
-- personas de la tienda. Borrar un comentario lo vacia y lo marca: un hilo con respuestas sigue en pie.
create table comentarios (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    proceso_id         bigint        not null,
    padre_id           bigint,
    bpmn_id            varchar(64),
    version_numero     integer,
    autor_id           bigint        not null,
    markdown           text          not null,
    html               text          not null,
    menciones          bigint[]      default '{}' not null,
    resuelto_por       bigint,
    resuelto_en        timestamp(6),
    editado_en         timestamp(6),
    eliminado_por      bigint,
    eliminado_en       timestamp(6),
    version            bigint        default 0 not null,
    creado_por         bigint,
    fecha_creacion     timestamp(6)  not null,
    modificado_por     bigint,
    fecha_modificacion timestamp(6)  not null,
    constraint fk_comentarios_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_comentarios_proceso foreign key (proceso_id) references procesos (id),
    constraint fk_comentarios_padre foreign key (padre_id) references comentarios (id),
    constraint fk_comentarios_autor foreign key (autor_id) references usuarios (id),
    constraint fk_comentarios_resuelto_por foreign key (resuelto_por) references usuarios (id),
    constraint fk_comentarios_eliminado_por foreign key (eliminado_por) references usuarios (id),
    constraint ck_comentarios_largo check (length(markdown) <= 10000),
    constraint ck_comentarios_menciones check (cardinality(menciones) <= 20),
    constraint ck_comentarios_version check (version_numero is null or version_numero > 0),
    -- Una respuesta no se ancla por su cuenta ni se resuelve: lo hace su hilo
    constraint ck_comentarios_respuesta check (padre_id is null
        or (bpmn_id is null and version_numero is null and resuelto_en is null))
);
create index idx_comentarios_empresa on comentarios (empresa_id);
create index idx_comentarios_proceso on comentarios (proceso_id, padre_id);
create index idx_comentarios_padre on comentarios (padre_id);
create index idx_comentarios_autor on comentarios (autor_id);
create index idx_comentarios_resuelto_por on comentarios (resuelto_por);
create index idx_comentarios_eliminado_por on comentarios (eliminado_por);

-- Lo que una persona tiene que saber. Siempre llega a esta tabla y al flujo en vivo; por correo segun su preferencia,
-- que se guarda en envio al crearla. correo_en es cuando su correo se resolvio: salio, o no hacia falta porque ya la
-- habia leido o la persona ya no esta. referencia_id senala lo que avisa dentro del proceso, como un comentario.
create table notificaciones (
    id            bigint        generated by default as identity primary key,
    empresa_id    bigint        not null,
    usuario_id    bigint        not null,
    tipo          varchar(30)   not null,
    autor_id      bigint,
    proceso_id    bigint,
    referencia_id bigint,
    envio         varchar(20)   not null,
    creada_en     timestamp(6)  not null,
    leida_en      timestamp(6),
    correo_en     timestamp(6),
    constraint fk_notificaciones_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_notificaciones_usuario foreign key (usuario_id) references usuarios (id),
    constraint fk_notificaciones_autor foreign key (autor_id) references usuarios (id),
    constraint fk_notificaciones_proceso foreign key (proceso_id) references procesos (id),
    constraint ck_notificaciones_tipo check (tipo in ('MENCION', 'RESPUESTA', 'HILO_RESUELTO')),
    constraint ck_notificaciones_envio check (envio in ('INMEDIATO', 'RESUMEN_DIARIO', 'NUNCA'))
);
create index idx_notificaciones_empresa on notificaciones (empresa_id);
create index idx_notificaciones_usuario on notificaciones (usuario_id, creada_en desc);
create index idx_notificaciones_autor on notificaciones (autor_id);
create index idx_notificaciones_proceso on notificaciones (proceso_id);
-- Lo que espera al resumen del dia, y lo leido que la purga borra a los 90 dias
create index idx_notificaciones_resumen on notificaciones (empresa_id, usuario_id)
    where envio = 'RESUMEN_DIARIO' and correo_en is null;
create index idx_notificaciones_leidas on notificaciones (leida_en) where leida_en is not null;

-- Como quiere cada persona el correo de cada tipo. Sin fila, el de por defecto del tipo.
create table preferencias_notificacion (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    usuario_id         bigint        not null,
    tipo               varchar(30)   not null,
    envio              varchar(20)   not null,
    fecha_modificacion timestamp(6)  not null,
    constraint fk_preferencias_notificacion_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_preferencias_notificacion_usuario foreign key (usuario_id) references usuarios (id),
    constraint uq_preferencias_notificacion unique (usuario_id, tipo),
    constraint ck_preferencias_notificacion_tipo check (tipo in ('MENCION', 'RESPUESTA', 'HILO_RESUELTO')),
    constraint ck_preferencias_notificacion_envio check (envio in ('INMEDIATO', 'RESUMEN_DIARIO', 'NUNCA'))
);
create index idx_preferencias_notificacion_empresa on preferencias_notificacion (empresa_id);

