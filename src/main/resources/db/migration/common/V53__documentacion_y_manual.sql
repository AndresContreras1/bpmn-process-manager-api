-- PR 62: la documentacion de un proceso y de cada elemento suyo, en Markdown, con el HTML ya saneado al lado. Una por
-- proceso y elemento: el proceso entero es la de bpmn_id vacio.
create table documentacion (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    proceso_id         bigint        not null,
    bpmn_id            varchar(64),
    markdown           text          not null,
    html               text          not null,
    version            bigint        default 0 not null,
    creado_por         bigint,
    fecha_creacion     timestamp(6)  not null,
    modificado_por     bigint,
    fecha_modificacion timestamp(6)  not null,
    constraint fk_documentacion_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_documentacion_proceso foreign key (proceso_id) references procesos (id),
    constraint ck_documentacion_largo check (length(markdown) <= 100000)
);
create index idx_documentacion_empresa on documentacion (empresa_id);
create unique index uq_documentacion on documentacion (proceso_id, coalesce(bpmn_id, ''));

-- La ficha de caracterizacion: lo que una organizacion dice de un proceso antes de dibujarlo.
create table caracterizaciones (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    proceso_id         bigint        not null,
    objetivo           varchar(4000),
    alcance            varchar(4000),
    entradas           varchar(4000),
    salidas            varchar(4000),
    proveedores        varchar(4000),
    clientes           varchar(4000),
    indicadores        varchar(4000),
    riesgos            varchar(4000),
    normativa          varchar(4000),
    version            bigint        default 0 not null,
    creado_por         bigint,
    fecha_creacion     timestamp(6)  not null,
    modificado_por     bigint,
    fecha_modificacion timestamp(6)  not null,
    constraint fk_caracterizaciones_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_caracterizaciones_proceso foreign key (proceso_id) references procesos (id),
    constraint uq_caracterizaciones_proceso unique (proceso_id)
);
create index idx_caracterizaciones_empresa on caracterizaciones (empresa_id);

