-- Un manual de una version, que arma la cola: el HTML y el PDF quedan en el almacen.
create table manuales (
    id             bigint        generated by default as identity primary key,
    empresa_id     bigint        not null,
    proceso_id     bigint        not null,
    version_numero integer       not null,
    idioma         varchar(10)   not null,
    estado         varchar(20)   not null,
    clave_html     varchar(255),
    clave_pdf      varchar(255),
    motivo         varchar(300),
    pedido_por     bigint,
    pedido_en      timestamp(6)  not null,
    listo_en       timestamp(6),
    constraint fk_manuales_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_manuales_proceso foreign key (proceso_id) references procesos (id),
    constraint fk_manuales_usuario foreign key (pedido_por) references usuarios (id),
    constraint ck_manuales_estado check (estado in ('PENDIENTE', 'DISPONIBLE', 'FALLIDO'))
);
create index idx_manuales_empresa on manuales (empresa_id);
create index idx_manuales_proceso on manuales (proceso_id);
create index idx_manuales_usuario on manuales (pedido_por);

