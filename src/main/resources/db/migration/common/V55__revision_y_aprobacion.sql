-- PR 64: como publica cada tienda. Sin fila publica directo, como siempre. Con aprobacion, una solicitud necesita
-- aprobaciones_necesarias aprobaciones de las personas de aprobadores o de las del rol de proceso rol_proceso_id. Con la
-- politica en DIRECTA lo demas se guarda, para volver a encenderla igual.
create table politicas_publicacion (
    id                      bigint        generated by default as identity primary key,
    empresa_id              bigint        not null,
    modo                    varchar(20)   not null,
    aprobaciones_necesarias integer       default 1 not null,
    rol_proceso_id          bigint,
    aprobadores             bigint[]      default '{}' not null,
    version                 bigint        default 0 not null,
    creado_por              bigint,
    fecha_creacion          timestamp(6)  not null,
    modificado_por          bigint,
    fecha_modificacion      timestamp(6)  not null,
    constraint fk_politicas_publicacion_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_politicas_publicacion_rol foreign key (rol_proceso_id) references roles_proceso (id),
    constraint uq_politicas_publicacion_empresa unique (empresa_id),
    constraint ck_politicas_publicacion_modo check (modo in ('DIRECTA', 'CON_APROBACION')),
    constraint ck_politicas_publicacion_necesarias check (aprobaciones_necesarias between 1 and 10),
    constraint ck_politicas_publicacion_aprobadores check (cardinality(aprobadores) <= 50),
    -- Una fuente o la otra. Que la elegida tenga a alguien lo comprueba el servicio al guardarla: la lista se puede
    -- quedar vacia si se anonimiza a quien estaba, y entonces nadie pide revisiones hasta que se arregle
    constraint ck_politicas_publicacion_fuente check (rol_proceso_id is null or cardinality(aprobadores) = 0)
);
create index idx_politicas_publicacion_rol on politicas_publicacion (rol_proceso_id);

-- Una solicitud congela el borrador de un proceso para que otras personas lo aprueben: la revision del borrador que
-- se guardo al pedirla, y la instantanea que se publicara si se aprueba (definicion, huella y BPMN, como una version),
-- con el numero que tendra y la version vigente contra la que se comparo. Los aprobadores se fijan al abrirla: son
-- los que la politica daba ese dia, sin quien la pidio. Solo una abierta por proceso. motivo dice por que una
-- aprobada no se publico. La revision puede irse con la limpieza de revisiones viejas: lo que se publica es la
-- instantanea, que la solicitud guarda.
create table solicitudes_publicacion (
    id                      bigint        generated by default as identity primary key,
    empresa_id              bigint        not null,
    proceso_id              bigint        not null,
    revision_id             bigint,
    solicitante_id          bigint        not null,
    estado                  varchar(25)   not null,
    markdown                text          default '' not null,
    html                    text          default '' not null,
    numero                  integer       not null,
    version_base            integer,
    huella                  varchar(64)   not null,
    definicion              text          not null,
    modelo_bpmn             text          not null,
    aprobaciones_necesarias integer       not null,
    aprobadores             bigint[]      not null,
    motivo                  varchar(2000),
    cerrada_por             bigint,
    cerrada_en              timestamp(6),
    version_publicada       integer,
    version                 bigint        default 0 not null,
    creado_por              bigint,
    fecha_creacion          timestamp(6)  not null,
    modificado_por          bigint,
    fecha_modificacion      timestamp(6)  not null,
    constraint fk_solicitudes_publicacion_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_solicitudes_publicacion_proceso foreign key (proceso_id) references procesos (id),
    constraint fk_solicitudes_publicacion_revision foreign key (revision_id) references revisiones_borrador (id)
        on delete set null,
    constraint fk_solicitudes_publicacion_solicitante foreign key (solicitante_id) references usuarios (id),
    constraint fk_solicitudes_publicacion_cerrada_por foreign key (cerrada_por) references usuarios (id),
    constraint ck_solicitudes_publicacion_estado check (estado in ('ABIERTA', 'PUBLICADA', 'APROBADA_SIN_PUBLICAR',
        'CAMBIOS_PEDIDOS', 'RECHAZADA', 'RETIRADA')),
    constraint ck_solicitudes_publicacion_largo check (length(markdown) <= 10000),
    constraint ck_solicitudes_publicacion_numero check (numero > 0),
    constraint ck_solicitudes_publicacion_necesarias check (aprobaciones_necesarias between 1 and 10),
    constraint ck_solicitudes_publicacion_aprobadores check (cardinality(aprobadores) <= 200),
    -- Abierta es lo mismo que sin cerrar
    constraint ck_solicitudes_publicacion_cierre check ((estado = 'ABIERTA') = (cerrada_en is null))
);
create unique index uq_solicitudes_publicacion_abierta on solicitudes_publicacion (proceso_id)
    where estado = 'ABIERTA';
create index idx_solicitudes_publicacion_empresa on solicitudes_publicacion (empresa_id, estado);
create index idx_solicitudes_publicacion_proceso on solicitudes_publicacion (proceso_id);
create index idx_solicitudes_publicacion_revision on solicitudes_publicacion (revision_id);
create index idx_solicitudes_publicacion_solicitante on solicitudes_publicacion (solicitante_id);
create index idx_solicitudes_publicacion_cerrada_por on solicitudes_publicacion (cerrada_por);

-- Lo que cada aprobador decidio: aprobar, pedir cambios o rechazar, con su comentario en Markdown y en HTML saneado.
-- Una decision por persona y solicitud.
create table aprobaciones (
    id            bigint        generated by default as identity primary key,
    empresa_id    bigint        not null,
    solicitud_id  bigint        not null,
    aprobador_id  bigint        not null,
    decision      varchar(20)   not null,
    markdown      text          default '' not null,
    html          text          default '' not null,
    fecha         timestamp(6)  not null,
    constraint fk_aprobaciones_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_aprobaciones_solicitud foreign key (solicitud_id) references solicitudes_publicacion (id),
    constraint fk_aprobaciones_aprobador foreign key (aprobador_id) references usuarios (id),
    constraint uq_aprobaciones_persona unique (solicitud_id, aprobador_id),
    constraint ck_aprobaciones_decision check (decision in ('APROBADA', 'CAMBIOS_PEDIDOS', 'RECHAZADA')),
    constraint ck_aprobaciones_largo check (length(markdown) <= 10000),
    -- Pedir cambios o rechazar siempre dice por que
    constraint ck_aprobaciones_motivo check (decision = 'APROBADA' or length(markdown) > 0)
);
create index idx_aprobaciones_empresa on aprobaciones (empresa_id);
create index idx_aprobaciones_aprobador on aprobaciones (aprobador_id);

-- Recertificacion: cada cuantos meses se revisa un proceso (12 si nadie dice otra cosa), y para que fecha de revision
-- ya se le aviso a su dueno que llego y que vencio. Se guarda la fecha avisada, no si se aviso: al moverse la fecha,
-- la nueva vuelve a tener sus dos avisos, y la misma nunca dos veces.
alter table procesos add column meses_entre_revisiones integer default 12 not null;
alter table procesos add column revision_avisada date;
alter table procesos add column vencida_avisada date;
alter table procesos add constraint ck_procesos_meses_entre_revisiones check (meses_entre_revisiones between 1 and 60);

-- Una revision del borrador tambien se guarda al pedir una aprobacion.
alter table revisiones_borrador drop constraint ck_revisiones_borrador_motivo;
alter table revisiones_borrador add constraint ck_revisiones_borrador_motivo
    check (motivo in ('AUTOGUARDADO', 'CIERRE', 'ANTES_DE_RESTAURAR', 'SOLICITUD'));

-- Los avisos de la revision y la aprobacion, y los de la recertificacion.
alter table notificaciones drop constraint ck_notificaciones_tipo;
alter table notificaciones add constraint ck_notificaciones_tipo check (tipo in ('MENCION', 'RESPUESTA',
    'HILO_RESUELTO', 'APROBACION_PEDIDA', 'SOLICITUD_APROBADA', 'SOLICITUD_PUBLICADA', 'SOLICITUD_SIN_PUBLICAR',
    'CAMBIOS_PEDIDOS', 'SOLICITUD_RECHAZADA', 'RECERTIFICACION_PENDIENTE', 'RECERTIFICACION_VENCIDA'));
alter table preferencias_notificacion drop constraint ck_preferencias_notificacion_tipo;
alter table preferencias_notificacion add constraint ck_preferencias_notificacion_tipo check (tipo in ('MENCION',
    'RESPUESTA', 'HILO_RESUELTO', 'APROBACION_PEDIDA', 'SOLICITUD_APROBADA', 'SOLICITUD_PUBLICADA',
    'SOLICITUD_SIN_PUBLICAR', 'CAMBIOS_PEDIDOS', 'SOLICITUD_RECHAZADA', 'RECERTIFICACION_PENDIENTE',
    'RECERTIFICACION_VENCIDA'));

