-- PR 31: la bitacora de cada tienda, encadenada para que se note si alguien la toca. Cada fila lleva su numero de
-- secuencia dentro de la tienda y el SHA-256 de sus campos junto con el de la anterior: cambiar o borrar una fila
-- rompe la cadena desde ahi, y GET /api/v1/auditoria/verificacion lo encuentra.
--
-- No guarda nombres ni correos, solo ids: no se puede cambiar, asi que no guarda nada que haya que seudonimizar.
-- Sobrevive a la baja de su tienda, que queda como lapida; actor_id no tiene clave foranea porque las personas si
-- se borran.
create table bitacora (
    id             bigint generated by default as identity primary key,
    empresa_id     bigint       not null,
    secuencia      bigint       not null,
    momento        timestamp(6) not null,
    actor_tipo     varchar(20)  not null,
    actor_id       bigint,
    accion         varchar(60)  not null,
    recurso        varchar(40),
    recurso_id     bigint,
    exito          boolean      not null,
    ip             varchar(45),
    user_agent     varchar(255),
    request_id     varchar(64),
    trace_id       varchar(32),
    detalle        text         not null,
    hash_anterior  varchar(64)  not null,
    hash           varchar(64)  not null,
    constraint fk_bitacora_empresa foreign key (empresa_id) references empresas (id),
    constraint uk_bitacora_secuencia unique (empresa_id, secuencia),
    constraint ck_bitacora_actor check (actor_tipo in ('USUARIO', 'SISTEMA', 'OPERADOR', 'CLAVE_DE_API'))
);
create index idx_bitacora_accion on bitacora (empresa_id, accion, secuencia);

-- Nada la cambia ni la borra, ni siquiera la API: un trigger lo rechaza. El rol con que se conecta la API, cuando
-- deje de ser el dueno de las tablas (PR 51), tendra solo INSERT y SELECT sobre ella.
create function bitacora_inmutable() returns trigger language plpgsql as $$
begin
    raise exception 'La bitacora no se cambia ni se borra' using errcode = 'insufficient_privilege';
end;
$$;
create trigger bitacora_sin_cambios before update or delete on bitacora
    for each row execute function bitacora_inmutable();
create trigger bitacora_sin_vaciar before truncate on bitacora
    for each statement execute function bitacora_inmutable();
