-- PR 61: los documentos de un proceso, o de uno de sus elementos (por su bpmn_id), con todas sus versiones. El archivo
-- vive en el almacen; aqui queda lo que se sabe de el y la clave donde esta.
create table documentos (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    proceso_id         bigint        not null,
    bpmn_id            varchar(64),
    nombre             varchar(150)  not null,
    version_actual     integer       not null,
    activo             boolean       default true not null,
    version            bigint        default 0 not null,
    creado_por         bigint,
    fecha_creacion     timestamp(6)  not null,
    modificado_por     bigint,
    fecha_modificacion timestamp(6)  not null,
    constraint fk_documentos_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_documentos_proceso foreign key (proceso_id) references procesos (id),
    constraint ck_documentos_version_actual check (version_actual > 0)
);
create index idx_documentos_empresa on documentos (empresa_id);
create index idx_documentos_proceso on documentos (proceso_id);

-- Cada archivo subido. Empieza PENDIENTE; la cola lo revisa (antivirus y, si es un ZIP por dentro, que no sea una
-- bomba) y lo deja DISPONIBLE o BLOQUEADO con el motivo. revisado dice si de verdad paso por un antivirus.
create table versiones_documento (
    id           bigint        generated by default as identity primary key,
    empresa_id   bigint        not null,
    documento_id bigint        not null,
    numero       integer       not null,
    nombre       varchar(150)  not null,
    tipo         varchar(100)  not null,
    tamano       bigint        not null,
    sha256       varchar(64)   not null,
    clave        varchar(255)  not null,
    estado       varchar(20)   not null,
    motivo       varchar(300),
    revisado     boolean       default false not null,
    subido_por   bigint,
    fecha        timestamp(6)  not null,
    constraint fk_versiones_documento_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_versiones_documento_documento foreign key (documento_id) references documentos (id) on delete cascade,
    constraint fk_versiones_documento_usuario foreign key (subido_por) references usuarios (id),
    constraint uq_versiones_documento unique (documento_id, numero),
    constraint uq_versiones_documento_clave unique (clave),
    constraint ck_versiones_documento_estado check (estado in ('PENDIENTE', 'DISPONIBLE', 'BLOQUEADO')),
    constraint ck_versiones_documento_tamano check (tamano > 0)
);
create index idx_versiones_documento_empresa on versiones_documento (empresa_id);
create index idx_versiones_documento_usuario on versiones_documento (subido_por);

-- El ancla diaria de la bitacora: el ultimo eslabon de cada tienda, copiado a un almacen donde nadie lo puede cambiar.
-- Si alguien reescribe la bitacora entera despues, su ultimo hash ya no coincide con el ancla de ese dia.
create table anclas_bitacora (
    id          bigint        generated by default as identity primary key,
    empresa_id  bigint        not null,
    dia         date          not null,
    secuencia   bigint        not null,
    hash        varchar(64)   not null,
    clave       varchar(255)  not null,
    inmutable   boolean       not null,
    fecha       timestamp(6)  not null,
    constraint fk_anclas_bitacora_empresa foreign key (empresa_id) references empresas (id),
    constraint uq_anclas_bitacora unique (empresa_id, dia)
);

