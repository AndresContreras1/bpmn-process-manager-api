-- PR 66: la exportacion completa de una tienda. Un administrador la pide, la cola la arma en un ZIP que va al almacen,
-- y el enlace para bajarla le llega por correo y vale 24 horas. Despues el ZIP se borra y la fila queda VENCIDA, como
-- constancia. sha256 es la huella del ZIP entero, y la del ultimo que hubo va al certificado de borrado de la tienda.
create table exportaciones (
    id          bigint        generated by default as identity primary key,
    empresa_id  bigint        not null,
    estado      varchar(20)   not null,
    pedida_por  bigint,
    pedida_en   timestamp(6)  not null,
    lista_en    timestamp(6),
    vence_en    timestamp(6),
    clave       varchar(255),
    tamano      bigint,
    sha256      varchar(64),
    archivos    integer,
    motivo      varchar(300),
    constraint fk_exportaciones_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_exportaciones_usuario foreign key (pedida_por) references usuarios (id),
    constraint ck_exportaciones_estado check (estado in ('PENDIENTE', 'LISTA', 'FALLIDA', 'VENCIDA')),
    -- Lista es lista entera: con su archivo, su huella y su vencimiento
    constraint ck_exportaciones_lista check (estado <> 'LISTA'
        or (clave is not null and sha256 is not null and tamano is not null and vence_en is not null))
);
create index idx_exportaciones_empresa on exportaciones (empresa_id);
create index idx_exportaciones_usuario on exportaciones (pedida_por);
-- Lo que la limpieza busca cada hora: las listas que vencieron y las pendientes que se quedaron atascadas
create index idx_exportaciones_estado on exportaciones (estado, vence_en);

-- Una sola en curso por tienda: el servicio lo comprueba con la tienda bloqueada, y la base lo garantiza.
create unique index uq_exportaciones_en_curso on exportaciones (empresa_id) where estado = 'PENDIENTE';

-- PR 51: como toda tabla de una tienda, solo sus filas.
alter table exportaciones enable row level security;
alter table exportaciones force row level security;
create policy aislamiento_por_tienda on exportaciones
    using (current_setting('app.sistema', true) = 'on'
           or empresa_id = nullif(current_setting('app.empresa_id', true), '')::bigint)
    with check (current_setting('app.sistema', true) = 'on'
                or empresa_id = nullif(current_setting('app.empresa_id', true), '')::bigint);
