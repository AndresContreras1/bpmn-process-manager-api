-- PR 68: el calendario laboral de cada tienda, los temporizadores que corren y los dos modos de un caso.

-- El calendario de la tienda: su pais (que dice que festivos se calculan), su zona horaria, su jornada y sus dias
-- habiles. Uno por tienda; mientras no lo edite, vale el de su pais con lunes a viernes de 8 a 17.
create table calendarios (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    pais               varchar(2)    not null,
    zona_horaria       varchar(40)   not null,
    hora_inicio        time          not null,
    hora_fin           time          not null,
    dias_habiles       varchar(70)   not null,
    version            bigint        default 0 not null,
    creado_por         bigint,
    fecha_creacion     timestamp(6)  not null,
    modificado_por     bigint,
    fecha_modificacion timestamp(6)  not null,
    constraint fk_calendarios_empresa foreign key (empresa_id) references empresas (id),
    constraint uq_calendarios_empresa unique (empresa_id),
    constraint ck_calendarios_pais check (pais in ('CO', 'US', 'FR', 'AU')),
    constraint ck_calendarios_jornada check (hora_inicio < hora_fin)
);

-- Lo que la tienda cambio de los festivos de su pais: un dia que agrega o renombra (festivo, con su nombre) o uno
-- calculado que quita (no festivo). Los calculados no se guardan: salen de la ley de cada pais, ano por ano.
create table festivos (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    fecha              date          not null,
    nombre             varchar(120),
    festivo            boolean       not null,
    version            bigint        default 0 not null,
    creado_por         bigint,
    fecha_creacion     timestamp(6)  not null,
    modificado_por     bigint,
    fecha_modificacion timestamp(6)  not null,
    constraint fk_festivos_empresa foreign key (empresa_id) references empresas (id),
    constraint uq_festivos unique (empresa_id, fecha),
    constraint ck_festivos_nombre check (festivo = false or nombre is not null)
);

-- Un caso corre en produccion (reloj de pared y calendario) o en prueba (los ticks y los socios simulados).
alter table casos add column modo varchar(20) default 'PRUEBA' not null;
alter table casos add constraint ck_casos_modo check (modo in ('PRODUCCION', 'PRUEBA'));

-- Una version de prueba prueba un borrador sin publicarlo: no tiene numero, nunca es la vigente y la purga se la lleva.
alter table versiones_proceso add column tipo varchar(20) default 'PUBLICADA' not null;
alter table versiones_proceso add constraint ck_versiones_proceso_tipo check (tipo in ('PUBLICADA', 'PRUEBA'));
alter table versiones_proceso drop constraint uk_versiones_proceso_numero;
alter table versiones_proceso drop constraint ck_versiones_proceso_numero;
alter table versiones_proceso add constraint ck_versiones_proceso_numero
    check (tipo = 'PUBLICADA' and numero > 0 or tipo = 'PRUEBA' and numero = 0);
create unique index uq_versiones_proceso_numero on versiones_proceso (proceso_id, numero) where tipo = 'PUBLICADA';

-- Una duracion en tiempo habil, contada con el calendario de la tienda.
alter table nodos_flujo drop constraint ck_nodos_flujo_tipo_temporizador;
alter table nodos_flujo add constraint ck_nodos_flujo_tipo_temporizador
    check (tipo_temporizador in ('DURACION', 'DURACION_HABIL', 'FECHA', 'CICLO'));

-- Un paso del caso copia el subtipo de su nodo, y TEMPORIZADOR_INTERMEDIO no cabia en 20: hasta ahora ningun
-- temporizador llegaba a un caso (E-18 no dejaba publicarlos). Mismo ancho que nodos_flujo.tipo_evento (V46).
alter table actividades_caso alter column subtipo type varchar(30);

-- La bitacora del caso cuenta cuando se arma un temporizador y cuando salta.
alter table eventos_caso drop constraint ck_eventos_caso_tipo;
alter table eventos_caso add constraint ck_eventos_caso_tipo check (tipo in ('CASO_ABIERTO', 'NODO_ACTIVADO',
    'TAREA_CREADA', 'TAREA_COMPLETADA', 'GATEWAY_DECIDIO', 'MENSAJE_ENVIADO', 'MENSAJE_RECIBIDO', 'ENVIO_FALLIDO',
    'SIN_CAMINO', 'VARIABLE_AUSENTE', 'CASO_TERMINADO', 'CASO_CANCELADO', 'TEMPORIZADOR_PROGRAMADO',
    'TEMPORIZADOR_DISPARADO'));

-- Los temporizadores armados: el de inicio de una version vigente (sin caso), la espera de un token y el de borde de
-- una actividad que espera. En produccion vencen en una hora (vence_en, UTC); en prueba, en un tick del reloj de la
-- tienda (vence_tick). Se toman con el caso bloqueado y la fila con FOR UPDATE SKIP LOCKED: saltan una sola vez.
create table temporizadores (
    id                 bigint        generated by default as identity primary key,
    empresa_id         bigint        not null,
    proceso_id         bigint        not null,
    version_proceso_id bigint        not null,
    caso_id            bigint,
    actividad_caso_id  bigint,
    nodo_id            bigint        not null,
    nodo_nombre        varchar(120)  not null,
    clase              varchar(20)   not null,
    modo               varchar(20)   not null,
    tipo_temporizador  varchar(20)   not null,
    expresion          varchar(120)  not null,
    interrumpe         boolean,
    vence_en           timestamp(6),
    vence_tick         integer,
    repeticiones       integer,
    disparos           integer       default 0 not null,
    intentos           integer       default 0 not null,
    ultimo_error       varchar(500),
    estado             varchar(20)   not null,
    creado_en          timestamp(6)  not null,
    disparado_en       timestamp(6),
    constraint fk_temporizadores_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_temporizadores_proceso foreign key (proceso_id) references procesos (id),
    constraint fk_temporizadores_version foreign key (version_proceso_id) references versiones_proceso (id),
    constraint fk_temporizadores_caso foreign key (caso_id) references casos (id),
    constraint fk_temporizadores_actividad foreign key (actividad_caso_id) references actividades_caso (id),
    constraint ck_temporizadores_clase check (clase in ('INICIO', 'INTERMEDIO', 'BORDE')),
    constraint ck_temporizadores_modo check (modo in ('PRODUCCION', 'PRUEBA')),
    constraint ck_temporizadores_tipo
        check (tipo_temporizador in ('DURACION', 'DURACION_HABIL', 'FECHA', 'CICLO')),
    constraint ck_temporizadores_estado check (estado in ('PROGRAMADO', 'DISPARADO', 'CANCELADO', 'FALLIDO')),
    constraint ck_temporizadores_vence check (modo = 'PRODUCCION' and vence_en is not null
                                              or modo = 'PRUEBA' and vence_tick is not null),
    constraint ck_temporizadores_caso check (clase = 'INICIO' and caso_id is null
                                             or clase <> 'INICIO' and caso_id is not null
                                                and actividad_caso_id is not null)
);
-- El planificador busca lo vencido de todas las tiendas; el tick, lo de una; el motor, lo de un caso.
create index idx_temporizadores_vencidos on temporizadores (estado, modo, vence_en);
create index idx_temporizadores_tick on temporizadores (empresa_id, estado, modo, vence_tick);
create index idx_temporizadores_caso on temporizadores (caso_id, empresa_id, estado);
create index idx_temporizadores_proceso on temporizadores (proceso_id);
create index idx_temporizadores_version on temporizadores (version_proceso_id);
create index idx_temporizadores_actividad on temporizadores (actividad_caso_id);
-- Un inicio temporizado armado por version y evento: sincronizarlos dos veces no arma dos. Los cancelados se quedan
-- como historia, y volver a ser la vigente arma uno nuevo.
create unique index uq_temporizadores_inicio on temporizadores (version_proceso_id, nodo_id)
    where clase = 'INICIO' and estado = 'PROGRAMADO';

