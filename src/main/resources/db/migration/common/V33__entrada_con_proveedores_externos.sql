-- PR 50: entrar con Google o Microsoft (OpenID Connect).

-- La identidad de una persona en un proveedor: el par (proveedor, sub) es como el proveedor la llama, y no cambia
-- aunque cambie el correo. Una identidad es de una sola persona.
create table identidades_externas (
    id           bigint generated by default as identity primary key,
    empresa_id   bigint       not null,
    usuario_id   bigint       not null,
    proveedor    varchar(30)  not null,
    sujeto       varchar(255) not null,
    email        varchar(254) not null,
    vinculada_en timestamp(6) not null,
    constraint fk_identidades_externas_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_identidades_externas_usuario foreign key (usuario_id) references usuarios (id),
    constraint uk_identidades_externas_sujeto unique (proveedor, sujeto)
);
create index idx_identidades_externas_usuario on identidades_externas (usuario_id);
create index idx_identidades_externas_empresa on identidades_externas (empresa_id);

-- Quien entra con un proveedor y ya tiene cuenta con ese correo no queda vinculado solo por eso: el enlace espera a
-- que confirme con su clave o su segundo factor. De su token solo se guarda el SHA-256.
create table vinculos_pendientes (
    id          bigint generated by default as identity primary key,
    empresa_id  bigint       not null,
    usuario_id  bigint       not null,
    proveedor   varchar(30)  not null,
    sujeto      varchar(255) not null,
    email       varchar(254) not null,
    token_hash  varchar(64)  not null,
    creado_en   timestamp(6) not null,
    vence_en    timestamp(6) not null,
    constraint fk_vinculos_pendientes_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_vinculos_pendientes_usuario foreign key (usuario_id) references usuarios (id),
    constraint uk_vinculos_pendientes_token unique (token_hash)
);
create index idx_vinculos_pendientes_empresa on vinculos_pendientes (empresa_id);

-- Los dominios de correo de una tienda. Una persona de un dominio verificado que entra con un proveedor por primera
-- vez se une a la tienda con el rol por defecto. Se verifica con un registro TXT en el DNS del dominio, y un dominio
-- solo lo puede tener verificado una tienda.
create table dominios_verificados (
    id               bigint generated by default as identity primary key,
    empresa_id       bigint       not null,
    dominio          varchar(253) not null,
    rol_por_defecto  varchar(20)  not null,
    token            varchar(64)  not null,
    creado_en        timestamp(6) not null,
    verificado_en    timestamp(6),
    constraint fk_dominios_verificados_empresa foreign key (empresa_id) references empresas (id),
    constraint uk_dominios_verificados_tienda unique (empresa_id, dominio),
    constraint ck_dominios_verificados_rol check (rol_por_defecto in ('ADMINISTRADOR', 'EDITOR', 'SOLO_LECTURA'))
);
create unique index uk_dominios_verificados_dominio on dominios_verificados (dominio) where verificado_en is not null;

-- La peticion de autorizacion de un login que esta en camino al proveedor: su state, su nonce y su verificador de
-- PKCE. La API no tiene sesion HTTP, asi que vive aqui, atada al navegador que la empezo por una cookie de la que
-- solo se guarda el SHA-256. Sirve una vez y no tiene tienda: todavia no se sabe quien es.
create table peticiones_oidc (
    estado_hash    varchar(64)  primary key,
    navegador_hash varchar(64)  not null,
    datos          text         not null,
    creada_en      timestamp(6) not null
);
create index idx_peticiones_oidc_creada on peticiones_oidc (creada_en);

-- La tienda puede pedir que su gente entre solo con un proveedor. Los administradores conservan la clave, para no
-- quedar fuera si el proveedor cae.
alter table configuracion_tienda add column solo_entrada_externa boolean default false not null;
