-- PR 49b: las passkeys (WebAuthn). Una passkey es un par de claves que guarda el dispositivo de la persona: la API
-- guarda solo la publica y verifica con ella lo que el dispositivo firma. Sirve de segundo factor y, como el
-- dispositivo pide la huella, el rostro o su PIN, tambien para entrar sin contrasena.

-- El identificador WebAuthn de la persona (user handle): 64 bytes al azar, creados con su primera passkey. No dice
-- nada de ella, a diferencia de su id o su correo, y es lo que el dispositivo devuelve al entrar sin clave.
alter table usuarios add column webauthn_id bytea;
alter table usuarios add constraint uk_usuarios_webauthn_id unique (webauthn_id);

-- Lo que la API necesita de cada passkey para verificarla: la clave publica (COSE), el contador de firmas, que solo
-- sube, y como se puede usar. Los mismos campos que el esquema de Spring Security, con la tienda de su dueno. La
-- atestacion del registro se guarda porque de ella se lee la clave en cada entrada.
create table passkeys (
    id                     bigint generated by default as identity primary key,
    empresa_id             bigint       not null,
    usuario_id             bigint       not null,
    credencial_id          bytea        not null,
    clave_publica          bytea        not null,
    contador_de_firmas     bigint       not null,
    uv_inicializado        boolean      not null,
    transportes            varchar(100) not null,
    respaldo_posible       boolean      not null,
    respaldada             boolean      not null,
    objeto_de_atestacion   bytea        not null,
    datos_del_cliente      bytea        not null,
    etiqueta               varchar(64)  not null,
    creada_en              timestamp(6) not null,
    ultimo_uso_en          timestamp(6),
    constraint fk_passkeys_empresa foreign key (empresa_id) references empresas (id),
    constraint fk_passkeys_usuario foreign key (usuario_id) references usuarios (id),
    constraint uk_passkeys_credencial unique (credencial_id)
);
create index idx_passkeys_empresa on passkeys (empresa_id);
create index idx_passkeys_usuario on passkeys (usuario_id);

-- PR 51: como toda tabla de una tienda, solo sus filas.
alter table passkeys enable row level security;
alter table passkeys force row level security;
create policy aislamiento_por_tienda on passkeys
    using (current_setting('app.sistema', true) = 'on'
           or empresa_id = nullif(current_setting('app.empresa_id', true), '')::bigint)
    with check (current_setting('app.sistema', true) = 'on'
                or empresa_id = nullif(current_setting('app.empresa_id', true), '')::bigint);

-- El desafio de cada ceremonia: las opciones que la API mando al navegador, para comprobar que lo que el dispositivo
-- firmo responde a ellas. La API no tiene sesion HTTP, asi que vive aqui, como las peticiones OIDC (V33). Sirve una
-- vez y vence a los cinco minutos; del id solo se guarda el SHA-256. Entrar sin clave empieza sin saber quien es, asi
-- que no tiene tienda; el de una persona se va con ella.
create table desafios_webauthn (
    id_hash     varchar(64)  primary key,
    proposito   varchar(20)  not null,
    usuario_id  bigint,
    opciones    text         not null,
    creado_en   timestamp(6) not null,
    constraint fk_desafios_webauthn_usuario foreign key (usuario_id) references usuarios (id) on delete cascade,
    constraint ck_desafios_webauthn_proposito check (proposito in ('REGISTRO', 'VERIFICACION', 'ENTRADA'))
);
create index idx_desafios_webauthn_usuario on desafios_webauthn (usuario_id);
create index idx_desafios_webauthn_creado on desafios_webauthn (creado_en);
